-- =============================================================================
-- 001 — Ужесточение аутентификации (изоляция данных между учётными записями)
-- =============================================================================
-- Что меняется в приложении:
--   * сервер требует Authorization: Bearer <token> на каждом запросе
--     (кроме /health и /auth/login);
--   * в sessions.token_hash пишется SHA-256 от токена, а не сам токен;
--   * личность и роль автора запроса берутся из сессии, а не из тела запроса.
--
-- Накатывать на уже работающую базу:
--   psql -U panorama -h localhost -d panorama -f db/migrations/001_auth_hardening.sql
--
-- Для новой базы ничего делать не нужно — всё уже есть в schema.sql.
-- =============================================================================

-- Без этого psql печатает десятки NOTICE вида
-- "ограничение ... не существует, пропускается" от DROP IF EXISTS.
SET client_min_messages = warning;

BEGIN;

-- 1. Разрешение токена выполняется на КАЖДОМ запросе — нужен индекс по хешу.
--    UNIQUE заодно защищает от коллизий и повторной вставки того же токена.
CREATE UNIQUE INDEX IF NOT EXISTS sessions_token_hash_uniq
    ON sessions (token_hash);

-- 2. Старые сессии хранят токен в открытом виде и по новой схеме сравнения
--    (по SHA-256) всё равно не сойдутся — отзываем их явно.
--    Пользователям нужно войти заново; это ожидаемое разовое действие.
UPDATE sessions
   SET revoked_at = now()
 WHERE revoked_at IS NULL;

-- 3. Подчистка: просроченные сессии не нужны и мешают читать таблицу.
DELETE FROM sessions
 WHERE expires_at < now() - interval '30 days';

COMMIT;

